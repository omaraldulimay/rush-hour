"""Generate rules/slo.rules.yml: the SLO recording rules for every SLO and window.

    python observability/prometheus/gen_slo_rules.py          # rewrite the file
    python observability/prometheus/gen_slo_rules.py --check  # exit 1 if the file is out of date

Four SLOs x four windows x four rule kinds are too repetitive to keep consistent by hand, so the
definitions live here and the YAML is generated (tests/test_observability.py fails on drift).

Per SLO and window w (5m, 30m, 1h, 6h) the rules record
    slo:requests:rate<w>          requests per second that count towards the SLI
    slo:sli_error_ratio:rate<w>   share of bad events (errors, or requests slower than the SLO)
    slo:burn_rate:rate<w>         error ratio / error budget (1 = budget is used up exactly at the
                                  end of the SLO window, 14.4 = 30 days of budget in 50 hours)
plus the constants slo:objective:ratio, slo:error_budget:ratio and the demo's budget gauge
slo:error_budget_remaining:ratio.
"""

import sys
from pathlib import Path

OUT = Path(__file__).parent / "rules" / "slo.rules.yml"
WINDOWS = ("5m", "30m", "1h", "6h")
# Prometheus keeps hours, not 30 days, so the "budget remaining" panel uses a 6 h demo window.
BUDGET_WINDOW = "6h"
OPS = "/healthz|/readyz|/metrics"

# name -> (objective, kind, selector, latency threshold bucket)
SLOS = {
    "checkout_availability": (0.995, "availability", 'service="checkout",route="/checkout"', None),
    # prometheus_client prints bucket edges as floats: le="1.0", not "1"
    "checkout_latency": (0.99, "latency", 'service="checkout",route="/checkout"', "1.0"),
    "catalog_availability": (0.999, "availability", f'service="catalog",route!~"{OPS}"', None),
    "catalog_latency": (0.99, "latency", f'service="catalog",route!~"{OPS}"', "0.3"),
}


def requests_expr(kind: str, sel: str, w: str) -> str:
    # 409 sold_out is a correct answer, so only 5xx counts as an error. A latency SLI looks at
    # the requests that were served (a 5xx has its own SLO).
    status = "" if kind == "availability" else ',status!~"5.."'
    return f"sum(rate(http_requests_total{{{sel}{status}}}[{w}]))"


def error_ratio_expr(kind: str, sel: str, le: str | None, w: str) -> str:
    if kind == "availability":
        errors = f'sum(rate(http_requests_total{{{sel},status=~"5.."}}[{w}])) or vector(0)'
        return f"({errors}) / ({requests_expr(kind, sel, w)} > 0)"
    fast = f'sum(rate(http_request_duration_seconds_bucket{{{sel},status!~"5..",le="{le}"}}[{w}]))'
    total = f'sum(rate(http_request_duration_seconds_count{{{sel},status!~"5.."}}[{w}]))'
    return f"1 - {fast} / ({total} > 0)"


def rule(record: str, expr: str, slo: str) -> str:
    return f"      - record: {record}\n        expr: {expr}\n        labels: {{ slo: {slo} }}\n"


def render() -> str:
    out = [
        "# GENERATED by gen_slo_rules.py (same folder): edit the generator, not this file.\n",
        "groups:\n",
    ]
    for slo, (objective, kind, sel, le) in SLOS.items():
        budget = round(1 - objective, 6)
        out.append(f"  - name: slo-{slo.replace('_', '-')}\n    rules:\n")
        for w in WINDOWS:
            out.append(rule(f"slo:requests:rate{w}", requests_expr(kind, sel, w), slo))
            out.append(
                rule(f"slo:sli_error_ratio:rate{w}", error_ratio_expr(kind, sel, le, w), slo)
            )
            out.append(
                rule(
                    f"slo:burn_rate:rate{w}",
                    f'slo:sli_error_ratio:rate{w}{{slo="{slo}"}} / {budget}',
                    slo,
                )
            )
        out.append(rule("slo:objective:ratio", f"vector({objective})", slo))
        out.append(rule("slo:error_budget:ratio", f"vector({budget})", slo))
        out.append(
            rule(
                "slo:error_budget_remaining:ratio",
                f'1 - slo:burn_rate:rate{BUDGET_WINDOW}{{slo="{slo}"}}',
                slo,
            )
        )
    return "".join(out)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.read_text() == text else 1)
    OUT.write_text(text)
    print(f"wrote {OUT}")
